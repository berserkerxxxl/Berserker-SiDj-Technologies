def check_windows_icon(binary: Path) -> None:
    """Read icon resources through Windows and compare every frame to our ICO."""
    import ctypes
    from ctypes import wintypes

    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    user = ctypes.WinDLL("user32", use_last_error=True)
    shell = ctypes.WinDLL("shell32", use_last_error=True)
    kernel.LoadLibraryExW.argtypes = [wintypes.LPCWSTR, ctypes.c_void_p, wintypes.DWORD]
    kernel.LoadLibraryExW.restype = ctypes.c_void_p
    kernel.FindResourceW.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]
    kernel.FindResourceW.restype = ctypes.c_void_p
    kernel.SizeofResource.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
    kernel.SizeofResource.restype = wintypes.DWORD
    kernel.LoadResource.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
    kernel.LoadResource.restype = ctypes.c_void_p
    kernel.LockResource.argtypes = [ctypes.c_void_p]
    kernel.LockResource.restype = ctypes.c_void_p
    kernel.FreeLibrary.argtypes = [ctypes.c_void_p]
    user.DestroyIcon.argtypes = [ctypes.c_void_p]
    shell.ExtractIconExW.argtypes = [wintypes.LPCWSTR, ctypes.c_int,
                                   ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p), ctypes.c_uint]
    shell.ExtractIconExW.restype = ctypes.c_uint
    module = kernel.LoadLibraryExW(str(binary), None, 0x2)  # LOAD_LIBRARY_AS_DATAFILE: do not execute.
    if not module:
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        def resource(kind: int, identifier: int) -> bytes:
            found = kernel.FindResourceW(module, identifier, kind)
            if not found:
                raise AssertionError(f"icon resource {kind}/{identifier} missing")
            size = kernel.SizeofResource(module, found)
            pointer = kernel.LockResource(kernel.LoadResource(module, found))
            assert size and pointer
            return ctypes.string_at(pointer, size)

        ico = (build.SOURCE / "assets/bs-reserve.ico").read_bytes()
        group = resource(14, 1)  # RT_GROUP_ICON; first resource generated by pinned rsrc.
        reserved, kind, count = struct.unpack_from("<HHH", ico)
        assert (reserved, kind) == (0, 1)
        assert struct.unpack_from("<HHH", group) == (0, 1, count)
        sizes = []
        for index in range(count):
            expected = struct.unpack_from("<BBBBHHII", ico, 6 + index * 16)
            embedded = struct.unpack_from("<BBBBHHIH", group, 6 + index * 14)
            assert expected[:7] == embedded[:7]
            width, height = expected[:2]
            assert width == height
            sizes.append(width or 256)
            size, offset = expected[6:]
            assert resource(3, embedded[7]) == ico[offset:offset + size]  # RT_ICON bytes.
        assert sorted(sizes) == [16, 20, 24, 32, 40, 48, 64, 96, 128, 256]
    finally:
        kernel.FreeLibrary(module)
    assert shell.ExtractIconExW(str(binary), -1, None, None, 0) == 1
    for size in ("large", "small"):
        icon = ctypes.c_void_p()
        try:
            count = shell.ExtractIconExW(str(binary), 0,
                                         ctypes.byref(icon) if size == "large" else None,
                                         ctypes.byref(icon) if size == "small" else None, 1)
            assert count == 1 and icon.value, (size, count, icon.value, ctypes.get_last_error())
        finally:
            if icon.value:
                user.DestroyIcon(icon)
    print("PASS Windows shell icon: one group, ten original frames, large and small icons load", flush=True)


def smoke(binary: Path, target: str, work: Path) -> None:
    if target == "windows_amd64":
        check_windows_icon(binary)
    root = work / "Тест архива с пробелами" / "Data"
    process = subprocess.Popen([str(binary), "--no-browser", "--data", str(root)],
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                               text=True, encoding="utf-8")
    lines: queue.Queue[str] = queue.Queue()
    threading.Thread(target=lambda: lines.put(process.stdout.readline()), daemon=True).start()
    try:
        url = lines.get(timeout=30).strip()
        if not re.fullmatch(r"http://127\.0\.0\.1:\d+", url):
            raise RuntimeError("program did not publish a loopback URL: " + repr(url))
        html = urllib.request.urlopen(url, timeout=10).read().decode("utf-8")
        token = re.search(r"const TOKEN='([a-f0-9]+)'", html).group(1)
        if build.CONFIG["version"] not in html:
            raise AssertionError("release version missing")

        def api(path: str, payload: dict | None = None):
            request = urllib.request.Request(url + path, headers={"X-BS-Token": token})
            if payload is not None:
                request.data = json.dumps(payload).encode("utf-8")
                request.add_header("Content-Type", "application/json")
            with urllib.request.urlopen(request, timeout=30) as response:
                return json.load(response)

        def action(name: str, **fields):
            api("/api/action", {"Action": name, **fields})
            until = time.monotonic() + 180
            while time.monotonic() < until:
                job = api("/api/job")
                if not job["Running"]:
                    if job["Error"]:
                        raise AssertionError(name + ": " + job["Error"])
                    return job["Result"]
                time.sleep(0.1)
            raise TimeoutError(name)

        state = api("/api/state")
        entry = build.TARGETS[target]
        assert state["OS"] == entry["os"] and state["Arch"] == entry["arch"]
        assert state["Version"] == build.CONFIG["version"] and state["Build"] == build.CONFIG["build"]
        assert state["Sources"] == []
        try:
            urllib.request.urlopen(url + "/api/state", timeout=10)
            raise AssertionError("API accepted unauthenticated request")
        except urllib.error.HTTPError as error:
            assert error.code == 403
        action("demo")
        state = api("/api/state")
        assert len(state["Sources"]) == 3 and len(state["Conversations"]) == 1
        assert len(state["Conversations"][0]["Revisions"]) == 2 and len(state["Notes"]) == 1
        action("demo")
        assert len(api("/api/state")["Sources"]) == 3
        action("note", Kind="instructions", Text="Synthetic cross-platform release test")
        assert len(api("/api/state")["Notes"]) == 2
        chat_id = state["Conversations"][0]["ID"]
        choices = api("/api/files?conversation=" + urllib.parse.quote(chat_id))
        picked = next(item for item in choices["Files"] if not item["Linked"])
        link = {"ConversationID": chat_id, "SourceID": picked["SourceID"], "FileIndex": picked["Index"]}
        action("file-link", **link)
        chat = api("/api/conversation?id=" + urllib.parse.quote(chat_id))
        assert any(item["Path"] == picked["Path"] for item in chat["Attachments"])
        assert not action("verify")["Errors"]
        repo = work / "Пробная копия" / "repository"
        credentials = {"Repository": str(repo), "Password": "Synthetic release test passphrase 2026!"}
        action("init", **credentials, Confirm=credentials["Password"])
        action("backup", **credentials)
        action("check-full", **credentials)
        snapshots = action("snapshots", **credentials)
        assert len(snapshots) == 1
        restored = action("restore", **credentials, Snapshot=snapshots[0]["ID"], Target=str(work / "Восстановлено"))
        assert restored["Checked"] > 0 and not restored["Errors"]
        migration = action("migration", Target=str(work / "Пакет на другом диске"))
        assert Path(migration["Path"]).parent == work / "Пакет на другом диске"
        package = Path(migration["Path"]).read_bytes()
        assert hashlib.sha256(package).hexdigest() == migration["SHA256"]
        with zipfile.ZipFile(io.BytesIO(package)) as archive:
            assert archive.testzip() is None
            assert any(name.endswith("index.html") for name in archive.namelist())
            manifest = json.loads(archive.read("FILES_MANIFEST.json"))
            assert len(manifest["FileLinks"]) == 1
            assert manifest["FileLinks"][0]["ConversationID"] == chat_id
            assert picked["Path"] in archive.read("index.html").decode("utf-8")
        action("file-link", **link, Remove=True)
        choices = api("/api/files?conversation=" + urllib.parse.quote(chat_id))
        assert not any(item["Manual"] for item in choices["Files"])
        action("shutdown")
        process.wait(timeout=20)
        assert process.returncode == 0
        print("PASS packaged executable:", target, "empty archive, token boundary, demo/dedup, notes, file link/unlink, SHA-256, encryption, full check, restore, offline migration with file links", flush=True)
    finally:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=10)
        error = process.stderr.read()
        if error:
            print(error)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("target", choices=build.TARGETS)
    parser.add_argument("--race", action="store_true")
    parser.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "bs-reserve-restic-cache")
    args = parser.parse_args()
    expected = build.TARGETS[args.target]
    goos = {"Darwin": "darwin", "Linux": "linux", "Windows": "windows"}[platform.system()]
    machine = {"x86_64": "amd64", "AMD64": "amd64", "aarch64": "arm64", "arm64": "arm64"}[platform.machine()]
    assert goos == expected["os"] and machine == expected["arch"], "native test on wrong runner"
    build.check_go()
    with tempfile.TemporaryDirectory(prefix="bs-reserve-native-") as temp:
        work = Path(temp)
        _, binary, restic = build.stage_bundle(args.target, work, args.cache.resolve())
        env = os.environ.copy()
        env["BS_TEST_RESTIC"] = str(restic)
        env["GOTOOLCHAIN"] = "local"
        if args.target == "windows_amd64":
            env["BS_TEST_SCHEDULER"] = "1"
            env["BS_TEST_FOLDER_DIALOG"] = "1"
        command = ["go", "test", "-count=1", "-v"]
        if args.race:
            command.append("-race")
        subprocess.run(command + ["./..."], cwd=build.SOURCE / "src", env=env, check=True)
        subprocess.run(["go", "vet", "./..."], cwd=build.SOURCE / "src", env=env, check=True)
        smoke(binary, args.target, work)


if __name__ == "__main__":
    main()
